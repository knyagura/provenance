#!/usr/bin/env python3
"""Inline the backend layer into app/index.html.

The app ships as ONE self-contained HTML file (no bundler, works offline as a PWA). The
backend code is kept as readable source in app/src/ and app/vendor/, and this script copies
it into index.html between the BACKEND markers. Re-run after editing either source file:

    python3 tools/build.py

It is idempotent: the block between the markers is replaced, never duplicated.
"""
from pathlib import Path
import re, sys

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "app" / "index.html"
VENDOR = ROOT / "app" / "vendor" / "supabase-js-2.117.3.umd.js"
BACKEND_JS = ROOT / "app" / "src" / "backend.js"
BACKEND_CSS = ROOT / "app" / "src" / "backend.css"
START, END = "<!-- BACKEND:START (generated by tools/build.py — edit app/src/*, not this block) -->", "<!-- BACKEND:END -->"

def main() -> int:
    html = INDEX.read_text(encoding="utf-8")
    vendor = VENDOR.read_text(encoding="utf-8")
    js = BACKEND_JS.read_text(encoding="utf-8")
    css = BACKEND_CSS.read_text(encoding="utf-8")
    for name, src in (("vendor", vendor), ("backend.js", js), ("backend.css", css)):
        if re.search(r"</(script|style)", src, re.I):
            print(f"refusing to inline {name}: it contains a closing </script> or </style> tag", file=sys.stderr)
            return 1
    block = (f"{START}\n<style>\n{css}\n</style>\n"
             f"<script>/* supabase-js 2.117.3 (MIT) — vendored, see app/vendor/ */\n{vendor}\n</script>\n"
             f"<script>\n{js}\n</script>\n{END}")
    if START in html:
        html = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, html, flags=re.S)
    else:
        idx = html.rfind("</body>")
        if idx < 0:
            print("no </body> in index.html", file=sys.stderr); return 1
        html = html[:idx] + block + "\n" + html[idx:]
    INDEX.write_text(html, encoding="utf-8")
    print(f"index.html rebuilt ({len(html)//1024} KB)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
